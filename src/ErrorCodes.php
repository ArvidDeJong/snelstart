    }

    /**
     * The part of the API a code belongs to ("Relaties" for REL-0007), or null when unknown.
     */
    public static function resource(string $code): ?string
    {
        return self::RESOURCES[substr($code, 0, 3)] ?? null;
    }

    /**
     * Every code in a text, such as a response body, each one once and in the order found. Only
     * the resources SnelStart documents count, so "ISO-8859" in an error page is not a code. A
     * number this list does not have yet is found too.
     *
     * @return list<string>
     */
    public static function find(string $text): array
    {
        preg_match_all('/(?<![A-Za-z0-9])(?:'.implode('|', array_keys(self::RESOURCES)).')-\d{4}(?!\d)/', $text, $matches);

        return array_values(array_unique($matches[0]));
    }
